"use client";

import { ArrowRight, Lock } from "lucide-react";
import { useEffect, useState } from "react";
import type { AssetDetail, AssetView } from "@/lib/asset-factory/views";
import type { Config } from "@/lib/asset-factory/types";
import { useFactory } from "./state";
import { CodeView, langOf } from "./md";

/** A live excerpt of one file from a package, fetched with the viewer's permissions. */
export default function PackagePeek({ assetId, path, lines = 22, title }: { assetId: string; path?: string; lines?: number; title?: string }) {
  const { fetchAsset, openAsset, navigate, view } = useFactory();
  const [d, setD] = useState<AssetDetail | null | undefined>(undefined);
  const seq = view?.seq;
  const persona = view?.actor.persona;
  useEffect(() => {
    let live = true;
    void fetchAsset(assetId).then((x) => live && setD(x));
    return () => { live = false; };
  }, [assetId, fetchAsset, seq, persona]);
  if (d === undefined) return <div className="af-skel" style={{ height: 160 }} />;
  if (d === null) return <div className="af-banner warn"><Lock size={15} /><div>This package isn&apos;t shared with {view?.actor.person.name} — the server returned nothing.</div></div>;
  const file = d.files.find((f) => f.path === (path ?? d.mainFile)) ?? d.files[0];
  if (!file) return null;
  const excerpt = file.content.split("\n").slice(0, lines).join("\n");
  return (
    <div className="af-card" style={{ padding: 0, overflow: "hidden" }}>
      <div className="af-file-head">
        <b className="af-mono">{d.asset.slug}</b><span className="af-muted af-mono">/{file.path}</span>
        {title && <span className="af-muted">· {title}</span>}
        <span className="af-spacer" />
        <button type="button" className="af-btn sm" onClick={() => navigate({ page: "asset", slug: d.asset.slug, tab: "files", path: file.path })}>Open package <ArrowRight size={12} /></button>
        {d.asset.runnable && <button type="button" className="af-btn sm ghost" onClick={() => openAsset(d.asset.id, "run")}>Try it</button>}
      </div>
      <CodeView code={excerpt + (file.content.split("\n").length > lines ? "\n…" : "")} lang={langOf(file.path)} maxHeight={360} />
    </div>
  );
}

/** agent.yaml for a set of assembled components — pins exact versions by reference. */
export function manifestYaml(name: string, blueprint: AssetView | undefined, parts: AssetView[], config?: Config): string {
  const refs = (t: AssetView["type"]) => parts.filter((p) => p.type === t);
  const list = (xs: AssetView[], f: (x: AssetView) => string) => (xs.length ? xs.map(f).join("\n") : "    []");
  const slugName = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return `# Generated by the Gemini 10 Asset Factory — every component pinned by version.
apiVersion: agents.gemini10/v1
kind: Agent
metadata:
  name: ${slugName}
${blueprint ? `  extends: ${blueprint.ref}\n` : ""}spec:
  runtime:
    model: gemini-3.5-flash
    region: us-central1
  skills:
${list(refs("skill"), (p) => `    - ${p.ref}`)}
  connectors:
${list(refs("connector"), (p) => `    - ref: ${p.ref}\n      secretRef: projects/<PROJECT_ID>/secrets/${p.slug.split("/")[1]}`)}
  workflows:
${list(refs("workflow"), (p) => `    - ${p.ref}`)}
${config ? `  parameters:
    plants: ${config.plants}
    exceptionsPerMonth: ${config.exceptionsPerMonth}
    autoResolveLimitUsd: ${config.autoResolveLimit}
    approvalChannel: "${config.approvalChannel}"
` : ""}  evaluation:
    suites:
${list(refs("evaluation"), (p) => `      - ${p.ref}`)}
    gate: all-thresholds-pass
`;
}
